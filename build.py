# --- the shared transformer step ---------------------------------------------


def matmul_int(dst, src, name, n_in, n_out, extra=""):
    # dst_j = scale_j * (sum_i src_i * int[i][j]) [+ extra]
    lines = []
    q, s = Q[name], S[name]
    for j in range(n_out):
        terms = []
        for i in range(n_in):
            c = q[i][j]
            if c == 0:
                continue
            terms.append(("+ " if c > 0 else "- ") + f"var(--{src}{i})*{abs(c)}")
        # leading literal zero because calc() has no unary minus on var terms.
        # a sum starting "- var(--a0)*12" is a parse error and the whole
        # property silently falls back to 0, which is a very quiet way to
        # lobotomize a dog.
        body = "0 " + " ".join(terms) if terms else "0"
        e = extra.format(j=j) if extra else ""
        lines.append(f"  --{dst}{j}: calc({fmt(s[j])} * ({body}){e});")
    return lines


def rms_lines(rvar, src, n):
    sq = " + ".join(f"var(--{src}{j})*var(--{src}{j})" for j in range(n))
    return [f"  --{rvar}: calc(1 / sqrt(({sq}) / {n} + {fmt(EPS)}));"]


cell = ["/* one transformer step, shared by every level */", ".cl {", "  display: inline;"]
for l in range(L):
    p = lp(l)
    xin = "x" if l == 0 else "xn"
    g1 = NORMS[f"g1{l}"]
    g2 = NORMS[f"g2{l}"]
    cell += rms_lines(f"{p}r1", xin, D)
    for j in range(D):
        cell.append(f"  --{p}a{j}: calc(var(--{xin}{j}) * var(--{p}r1) * {fmt(g1[j])});")
    cell += matmul_int(f"{p}q", f"{p}a", f"wq{l}", D, D)
    cell += matmul_int(f"{p}k", f"{p}a", f"wk{l}", D, D)
    cell += matmul_int(f"{p}v", f"{p}a", f"wv{l}", D, D)
    # rope happens in the per level rules. attention output --{p}o too.
    for j in range(D):
        cell.append(f"  --{p}xm{j}: calc(var(--{xin}{j}) + var(--{p}om{j}));")
    cell += rms_lines(f"{p}r2", f"{p}xm", D)
    for j in range(D):
        cell.append(f"  --{p}b{j}: calc(var(--{p}xm{j}) * var(--{p}r2) * {fmt(g2[j])});")
    cell += matmul_int(f"{p}gt", f"{p}b", f"wg{l}", D, MLP)
    cell += matmul_int(f"{p}up", f"{p}b", f"wu{l}", D, MLP)
    for j in range(MLP):
        cell.append(f"  --{p}sg{j}: calc(var(--{p}gt{j}) / (1 + exp(-1 * var(--{p}gt{j}))));")
        cell.append(f"  --{p}ac{j}: calc(var(--{p}sg{j}) * var(--{p}up{j}));")
    out = "xn" if l == 0 else "uxn"
    # down projection with the residual folded in
    qd, sd = Q[f"wd{l}"], S[f"wd{l}"]
    for j in range(D):
        terms = []
        for i in range(MLP):
            c = qd[i][j]
            if c == 0:
                continue
            terms.append(("+ " if c > 0 else "- ") + f"var(--{p}ac{i})*{abs(c)}")
        body = "0 " + " ".join(terms) if terms else "0"
        cell.append(f"  --{out}{j}: calc(var(--{p}xm{j}) + {fmt(sd[j])} * ({body}));")
gf = NORMS["gf"]
cell += rms_lines("rf", "uxn", D)
for j in range(D):
    cell.append(f"  --f{j}: calc(var(--uxn{j}) * var(--rf) * {fmt(gf[j])});")
cell.append("}")
css.append("\n".join(cell))
css.append("")

# wo matmul needs its own name (--om) because attention out --o is per level
womm = [".cl {"]
for l in range(L):
    p = lp(l)
    womm += matmul_int(f"{p}om", f"{p}o", f"wo{l}", D, D)
womm.append("}")
css.append("\n".join(womm))
