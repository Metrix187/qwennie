# same math as the stylesheet, plain python floats

import numpy as np  # only for convenience arrays in the reference pass

DQn = {k: np.array(v) for k, v in DQ.items()}
NRM = {k: np.array(v) for k, v in NORMS.items()}


def rms(x, g):
    r = 1.0 / math.sqrt(float((x * x).mean()) + EPS)
    return x * r * g


def sample(qtext, salt, tamp):
    ids = [PAD] * (PROMPT - 2 - len(qtext.split())) + [USR] + [stoi[x] for x in qtext.split()] + [BOT]
    kc = [[None] * L for _ in range(T)]
    vc = [[None] * L for _ in range(T)]

    def step(pos, tok):
        x = DQn["emb"][tok].copy()
        for l in range(L):
            a = rms(x, NRM[f"g1{l}"])
            q = (a @ DQn[f"wq{l}"]).reshape(HEADS, HD)
            k = (a @ DQn[f"wk{l}"]).reshape(HEADS, HD)
            v = (a @ DQn[f"wv{l}"]).reshape(HEADS, HD)
            for h in range(HEADS):
                for fq in range(HD // 2):
                    c, s = COS[pos][fq], SIN[pos][fq]
                    qe, qo = q[h, 2 * fq], q[h, 2 * fq + 1]
                    ke, ko = k[h, 2 * fq], k[h, 2 * fq + 1]
                    q[h, 2 * fq], q[h, 2 * fq + 1] = qe * c - qo * s, qe * s + qo * c
                    k[h, 2 * fq], k[h, 2 * fq + 1] = ke * c - ko * s, ke * s + ko * c
            kc[pos][l], vc[pos][l] = k, v
            o = np.zeros(D)
            for h in range(HEADS):
                sc = [float(q[h] @ kc[i][l][h]) / SQ for i in range(pos + 1)]
                mx = max(sc)
                es = [math.exp(z - mx) for z in sc]
                tot = sum(es)
                acc = np.zeros(HD)
                for i in range(pos + 1):
                    acc += (es[i] / tot) * vc[i][l][h]
                o[h * HD : (h + 1) * HD] = acc
            x = x + o @ DQn[f"wo{l}"]
            b = rms(x, NRM[f"g2{l}"])
            gate = b @ DQn[f"wg{l}"]
            up = b @ DQn[f"wu{l}"]
            x = x + ((gate / (1 + np.exp(-gate))) * up) @ DQn[f"wd{l}"]
        return rms(x, NRM["gf"]) @ DQn["lm"]

    for pos, tok in enumerate(ids):
        logits = step(pos, tok)
    s = salt
    words = []
    done = False
    cur = None
    for n in range(GEN):
        if cur is not None:
            logits = step(PROMPT + n - 1, cur)
        lj = [logits[k] + k * TIE + tamp * (((s * PJ[k]) % 97) / 96 - 0.5) for k in range(V)]
        cur = max(range(V), key=lambda kk: lj[kk])
        s = (s * 137 + 29) % 251
        if cur == END:
            done = True
        words.append("" if done else glyph_text(VOCAB[cur]))
    return "".join(words)


