# compiles weights.json into model.css + index.html + expected.json.
# style.css is hand written. rerun me after every retrain.
#
# the shape of the thing: every token position is one nesting level of the
# dom. each level's cell runs the full transformer step in shared css rules
# (rmsnorm, int8 matmuls in calc, swiglu, lm head, argmax). what CAN'T be
# shared is anything positional: rope angles are literals per level, the kv
# cache write goes to that level's named slots, and attention reads however
# many positions exist below it. those get generated per level, which is why
# this file emits a few megabytes. attention is o(t^2) in css just like in
# real life, except here the t^2 is bytes.

import json
import math

w = json.load(open("weights.json"))
VOCAB = w["vocab"]
V = len(VOCAB)
T, PROMPT = w["T"], w["PROMPT"]
GEN = T - PROMPT
D, L, HEADS, HD, MLP = w["D"], w["L"], w["HEADS"], w["HD"], w["MLP"]
EPS = w["eps"]
PJ = w["P"]
COS, SIN = w["cos"], w["sin"]
Q = w["Q"]
S = w["S"]
NORMS = w["norms"]
N_PARAMS = w["n_params"]
stoi = {t: i for i, t in enumerate(VOCAB)}
PAD, USR, BOT, END = 0, 1, 2, 3
SQ = math.sqrt(HD)

TIE = 1e-5
SEPS = 1e-7

QUESTIONS = [
    "hello",
    "who are you ?",
    "how do you work ?",
    "what is css ?",
    "do you like treats ?",
    "tell me about your day",
    "are you a real llm ?",
    "can you help me ?",
    "who is yipsy ?",
    "do you use javascript ?",
    "good girl",
    "tell me a joke",
]
ROLLS = [("r1", 3, "🎾"), ("r2", 47, "🦴"), ("r3", 101, "🧸"), ("r4", 199, "🍖")]
TAMPS = [("sleepy", 0.6), ("waggy", 1.6), ("zoomies", 3.2)]
DEFAULT_Q, DEFAULT_ROLL, DEFAULT_TAMP = 1, "r1", "waggy"

# dequantized float weights, exactly what the stylesheet computes with
DQ = {k: [[Q[k][i][j] * S[k][j] for j in range(len(S[k]))] for i in range(len(Q[k]))] for k in Q}


def fmt(x):
    # full double precision, trimmed. parity with python floats depends on it
    r = repr(float(x))
    return "0" if r in ("0.0", "-0.0") else r


def sgn_term(x):
    return f"- {fmt(-x)}" if x < 0 else f"+ {fmt(x)}"


