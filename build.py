gc.append("  --gmx: max(" + ", ".join(f"var(--lg{k})" for k in range(V)) + ");")
argmax = " + ".join(f"{k} * max(0, sign(var(--lg{k}) - var(--gmx) + {fmt(SEPS)}))" for k in range(1, V))
gc.append(f"  --np: calc({argmax});")
gc.append(f"  --s2: calc(mod(var(--sd) * 137 + 29, 251));")
gc.append(f"  --d2: max(var(--dn), calc(1 - min(1, abs(var(--np) - {END}))));")
gc.append("}")
css.append("\n".join(gc))
css.append("")

