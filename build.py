# --- per level rules: rope, kv write, attention read --------------------------

lev = ["/* positional rules. rope angles and attention width are per level */"]
for pos in range(T - 1):
    lines = [f".cl.p{pos} {{"]
    for l in range(L):
        p = lp(l)
        # rotate q and k with this position's angles, write the kv slots
        for h in range(HEADS):
            for fq in range(HD // 2):
                c, s = fmt(COS[pos][fq]), fmt(SIN[pos][fq])
                e, o = h * HD + 2 * fq, h * HD + 2 * fq + 1
                lines.append(f"  --{p}qr{e}: calc(var(--{p}q{e})*{c} - var(--{p}q{o})*{s});")
                lines.append(f"  --{p}qr{o}: calc(var(--{p}q{e})*{s} + var(--{p}q{o})*{c});")
                lines.append(f"  --{p}kr{e}: calc(var(--{p}k{e})*{c} - var(--{p}k{o})*{s});")
                lines.append(f"  --{p}kr{o}: calc(var(--{p}k{e})*{s} + var(--{p}k{o})*{c});")
        for j in range(D):
            lines.append(f"  --K{l}p{pos}j{j}: var(--{p}kr{j});")
            lines.append(f"  --V{l}p{pos}j{j}: var(--{p}v{j});")
        # attention over positions 0..pos (this level's own k comes from its
        # freshly written slot vars? no — from the local --kr, same values)
        for h in range(HEADS):
            for i in range(pos + 1):
                dot = " + ".join(
                    f"var(--{p}qr{h*HD+j})*var(--K{l}p{i}j{h*HD+j})" if i < pos else
                    f"var(--{p}qr{h*HD+j})*var(--{p}kr{h*HD+j})"
                    for j in range(HD)
                )
                lines.append(f"  --s{l}{h}i{i}: calc(({dot}) / {fmt(SQ)});")
            mx = ", ".join(f"var(--s{l}{h}i{i})" for i in range(pos + 1))
            lines.append(f"  --mx{l}{h}: max({mx});")
            den = " + ".join(f"exp(var(--s{l}{h}i{i}) - var(--mx{l}{h}))" for i in range(pos + 1))
            lines.append(f"  --dnm{l}{h}: calc({den});")
            for j in range(HD):
                col = h * HD + j
                num = " + ".join(
                    f"exp(var(--s{l}{h}i{i}) - var(--mx{l}{h})) * "
                    + (f"var(--V{l}p{i}j{col})" if i < pos else f"var(--{p}v{col})")
                    for i in range(pos + 1)
                )
                lines.append(f"  --{p}o{col}: calc(({num}) / var(--dnm{l}{h}));")
    lines.append("}")
    lev.append("\n".join(lines))
css.append("\n".join(lev))
css.append("")

# --- lm head, jitter, argmax (gen cells only) ---------------------------------

gc = ["/* lm head + argmax. only levels that actually speak pay for this */", ".gc {"]
